describe('DEFECT 07/10/11/12/14 layout structures & quality gates', () => {
  it('reading order: full-width title, then col 1 completely, then col 2', () => {
    const lines = [L('TWO COLUMN TITLE THAT SPANS THE WHOLE PAGE WIDTH OK', 50, 100, 500)]
    for (let i = 0; i < 4; i++) {
      lines.push(L(`left column text line number ${i}`, 50, 140 + i * 20, 230))
      lines.push(L(`right column text line number ${i}`, 330, 140 + i * 20, 230))
    }
    const t = reconstructPageLayout(lines, W, H).fullText
    expect(t.indexOf('left column text line number 3')).toBeLessThan(t.indexOf('right column text line number 0'))
    expect(t.indexOf('TWO COLUMN')).toBeLessThan(t.indexOf('left column text line number 0'))
  })

  it('tables: merged spanning header emitted once + wrapped cell joined', () => {
    const lines = [L('ENTERPRISE CLUSTER MATRIX', 50, 100, 500)]
    const rows = [['Name', 'CPU', 'RAM', 'Cost'], ['alpha', '8', '32', '120'], ['beta', '16', '64', '240']]
    rows.forEach((r, ri) => r.forEach((c, ci) => lines.push(L(c, 50 + ci * 130, 140 + ri * 30, 80))))
    const r = reconstructPageLayout(lines, W, H)
    expect(r.tables).toHaveLength(1)
    expect(r.tables[0].html).toContain('colspan="4"')
    expect(r.fullText.split('ENTERPRISE CLUSTER MATRIX').length - 1).toBe(1)
    expect(r.tables[0].markdown).toContain('| alpha | 8 | 32 | 120 |')

    const wrapLs = [
      L('Reporting', 50, 100, 80), L('Status', 200, 100, 80), L('Category', 50, 118, 80),
      L('alpha', 50, 160, 80), L('ok', 200, 160, 80), L('beta', 50, 200, 80), L('bad', 200, 200, 80),
    ]
    expect(reconstructPageLayout(wrapLs, W, H).tables[0].markdown).toContain('Reporting Category')
  })

  it('code blocks preserve 4-space grid and validate bracket balance', () => {
    const cw = 7
    const src = ['def convert(path):', '    header = read(path)', '    if header:', '        return 1', '    return 0']
    const lines = src.map((s, i) => L(s.trim(), 50 + (s.length - s.trimStart().length) * cw, 200 + i * 18, s.trim().length * cw))
    const r = reconstructPageLayout(lines, W, H)
    expect(r.fullText).toContain('```')
    expect(r.fullText).toContain('\n        return 1')
    expect(r.codeBlocks[0].balanced).toBe(true)
    expect(validateCodeBrackets('def foo(x:\n    return 1').balanced).toBe(false)
  })

  it('preserves 7 nested bullet levels and structured listTree', () => {
    const lines = Array.from({ length: 7 }, (_, i) => L(`• Level ${i + 1} item`, 50 + i * 15, 160 + i * 20, 140))
    const r = reconstructPageLayout(lines, W, H)
    expect(r.fullText).toContain('\n            - Level 7 item')
    expect(r.listTree).toHaveLength(1)
  })

  it('detects checkbox, radio, text line, signature, and date fields', () => {
    const ls = [
      { text: '[ ] Agree to terms', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: '[x] Subscribe', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: '( ) 3- Good', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: '(X) 4- Excellent', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: 'Comments: ________________', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: 'Signature: ________', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: 'Date: 2026-10-31', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
    ]
    const f = detectFormFields(ls)
    expect(f.filter(x => x.type === 'checkbox')).toHaveLength(2)
    expect(f.filter(x => x.type === 'radio' && x.state === 'checked')).toHaveLength(1)
    expect(f.filter(x => x.type === 'text')).toHaveLength(1)
    expect(f.filter(x => x.type === 'signature')).toHaveLength(1)
    expect(f.find(x => x.type === 'date')?.value).toBe('2026-10-31')
  })

  it('evaluates quality gates & generates valid .docx export blob', async () => {
    const p = buildPageResult({
      ocrLines: [L('Hello world', 50, 150, 120), L('Weak line', 50, 200, 100, 14, 'ocr', 0.72)],
      width: W, height: H, pageNumber: 1,
    })
    const gates = evaluateQualityGates([p])
    expect(gates.passed).toBe(true)
    expect(gates.fragmentCount).toBe(0)
    expect(gates.duplicateCount).toBe(0)
    expect(gates.reviewQueue).toHaveLength(1)
    expect(auditPageCoverage(p.lines, p.lines).uncoveredCount).toBe(0)

    const docxBlob = await buildOcrDocxBlob([p], 'test-ocr')
    expect(docxBlob.size).toBeGreaterThan(1000)
  })
})

describe('TASK #1-#5 Code syntax, JWT validation, per-run emoji font, detached bullets, & α/A0', () => {
  it('#1 repairs f-string brace mismatch and call-arg trailing period', () => {
    const broken = [
      'def parse(pdf_bytes):',
      '    raise SecurityValidationError(f"Disallowed payload: {detected_format)")',
      '    return ConversionResult(',
      '        output_size_bytes=len(pdf_bytes).',
      '        status="ok"',
      '    )',
    ].join('\n')
    const fixed = repairCodeSyntax(broken)
    expect(fixed).toContain('{detected_format}')
    expect(fixed).toContain('output_size_bytes=len(pdf_bytes),')
    expect(validateCodeBrackets(fixed).balanced).toBe(true)
  })

  it('#2 validates JWT Base64URL header/payload JSON and Iz4 -> lz4', () => {
    const validJwt = 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.sig'
    const invalidJwt = 'eyJhbGciOiJIUzI1NiJ9.not!valid!base64.sig'
    expect(validateJwtToken(validJwt).valid).toBe(true)
    expect(validateJwtToken(invalidJwt).valid).toBe(false)
    expect(repairProtectedToken('compression=Iz4')).toBe('compression=lz4')
  })

  it('#3 splits mixed Latin + Emoji/Checkmark lines per font with zero dropped glyphs', () => {
    const latin = new Set([...Array.from('CheckPassed01%:() ').map(c => c.codePointAt(0))])
    const symbol = new Set([0x1F680, 0x1F4CA, 0x26A1, 0x2713, 0x2699])
    const fonts = [{ key: 'arial', set: latin }, { key: 'symbol', set: symbol }]
    const res = segmentTextByFont(fonts, '🚀 📊 ⚡ ⚙️ (Check: ✓ 100% Passed)')
    expect(res.skipped).toBe(0)
    expect(res.runs.some(r => r.f.key === 'symbol' && r.text.includes('🚀'))).toBe(true)
    expect(res.runs.some(r => r.f.key === 'arial' && r.text.includes('Passed'))).toBe(true)
  })

  it('#4 re-attaches detached hanging bullet markers instead of flattening into prose', () => {
    const ls = [
      L('Global Infrastructure Layer', 50, 140, 180),
      L('•', 50, 165, 10),
      L('Primary Data Centers', 72, 165, 160),
      L('◦', 72, 185, 10),
      L('US-East Cluster', 94, 185, 130),
    ]
    const r = reconstructPageLayout(ls, W, H)
    expect(r.fullText).toContain('Global Infrastructure Layer')
    expect(r.fullText).toContain('\n- Primary Data Centers')
    expect(r.fullText).toContain('\n  - US-East Cluster')
    expect(r.listTree[0].children).toHaveLength(1)
  })

  it('#5 repairs statistical α and table-column AO -> A0', () => {
    expect(fixFieldConfusables('a Level (1 - a) Specimen AO')).toBe('α Level (1 - α) Specimen A0')
    const ls = [
      L('Code', 50, 100, 60), L('Mean ± SD', 200, 100, 100),
      L('A1', 50, 130, 40), L('12.4 ± 0.3', 200, 130, 80),
      L('AO', 50, 160, 40), L('10.1 ± 0.2', 200, 160, 80),
    ]
    const r = reconstructPageLayout(ls, W, H)
    expect(r.tables[0].markdown).toContain('| A0 | 10.1 ± 0.2 |')
  })

  it('/goal validates PUA symbols, XNO->✗ No, angle brackets <>, CTC multiChar JWT beam, & OpenXML DOCX', async () => {
    expect(normalizePuaSymbols('\uF0FC Included \uF0FB No \uF0FE Yes \uF0A3 Box')).toBe('✓ Included ✗ No ☑ Yes ☐ Box')
    expect(fixFieldConfusables('XNO √ Included √ Digitally Signed')).toBe('✗ No ✓ Included ✓ Digitally Signed')

    expect(validateCodeBrackets('def f(x: List<str>) -> bool:\n    return len(x) < 10').balanced).toBe(true)
    expect(validateCodeBrackets('def f(x: List<str):').balanced).toBe(false)

    // Simulate a JWT where "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9" has an ambiguous 'I' vs 'l' inside "cCI6"
    const jwtStr = 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiIxMjM0In0.sig'
    const ambIdx = jwtStr.indexOf('cCI6') + 2
    const charMatrix = Array.from(jwtStr).map((ch, idx) =>
      idx === ambIdx
        ? [{ t: 'l', mean: 0.55 }, { t: 'I', mean: 0.45 }]
        : [{ t: ch, mean: 0.99 }]
    )
    const decoded = decodeWithCtcMultiChar(charMatrix, 'jwt')
    expect(decoded).toBe(jwtStr)
    expect(validateJwtToken(decoded).valid).toBe(true)

    const p = buildPageResult({
      ocrLines: [
        L('Section 01: Multi-Level & Symbols 🚀 ✓', 50, 110, 300),
        L('• Item one', 50, 150, 120),
        L('• Sub item', 80, 170, 120),
        L('1. Legal outline', 50, 200, 140),
        L('1.1 Sub clause', 70, 220, 140),
      ],
      width: W, height: H, pageNumber: 1,
    })
    const blob = await buildOcrDocxBlob([p], 'goal-verify')
    const gate = await verifyDocxBlob(blob)
    expect(gate.ok).toBe(true)
  })
})
