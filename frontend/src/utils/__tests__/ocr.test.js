import { describe, it, expect } from 'vitest'
import {
  toScript, detectScript, fixFieldConfusables, normalizePunctuation, similarity,
} from '../ocrPostProcess.js'
import { reconstructPageLayout, detectFormFields } from '../ocrLayoutAnalysis.js'
import { buildPageResult } from '../paddleOcr.js'
import { isNativeGood } from '../nativeText.js'

// line helper: text, x, y(top), width, height, source, mean
const L = (text, x, y, w, h = 14, source = 'ocr', mean = 0.97) => ({
  text, source, mean,
  box: [[x, y], [x + w, y], [x + w, y + h], [x, y + h]],
})
const W = 600
const H = 800

describe('BUG-04 sub/superscripts', () => {
  it('maps chemistry and math runs', () => {
    expect(toScript('2', 'sub').uni).toBe('₂')
    expect(toScript('4', 'sub').uni).toBe('₄')
    expect(toScript('n-1', 'sup').uni).toBe('ⁿ⁻¹')
    expect(toScript('2', 'sup').uni).toBe('²')
  })
  it('never drops unmappable runs', () => {
    expect(toScript('q!', 'sup').uni).toBe('^(q!)')
  })
})

describe('BUG-03 script detection', () => {
  it('votes by Unicode range', () => {
    expect(detectScript('Привет мир')).toBe('cyrillic')
    expect(detectScript('שלום עולם')).toBe('hebrew')
    expect(detectScript('नमस्ते')).toBe('devanagari')
    expect(detectScript('こんにちは')).toBe('cjk')
    expect(detectScript('Hello')).toBe('latin')
  })
})

describe('BUG-08 field-typed fixes', () => {
  it('euro read as E', () => {
    expect(fixFieldConfusables('(E3,120,000.00)')).toBe('(€3,120,000.00)')
  })
  it('id digits', () => {
    expect(fixFieldConfusables('EVT-9OOO2')).toBe('EVT-90002')
    expect(fixFieldConfusables('EVT-90002')).toBe('EVT-90002')
  })
  it('check mark', () => {
    expect(fixFieldConfusables('(Check: √ 100% Passed)')).toBe('(Check: ✓ 100% Passed)')
  })
  it('leaves words and hashes alone', () => {
    expect(fixFieldConfusables('Hello world')).toBe('Hello world')
    expect(fixFieldConfusables('SHA-256 checksum')).toBe('SHA-256 checksum')
  })
})

describe('BUG-12 punctuation', () => {
  it('fixes & spacing and stray dot', () => {
    expect(normalizePunctuation('Confidential&.')).toBe('Confidential &')
    expect(normalizePunctuation('Confidential& Automated')).toBe('Confidential & Automated')
    expect(normalizePunctuation('party \'s')).toBe("party's")
  })
  it('leaves R&D, urls, code', () => {
    expect(normalizePunctuation('R&D team')).toBe('R&D team')
    expect(normalizePunctuation('https://a.b/c&.d')).toBe('https://a.b/c&.d')
  })
})

describe('BUG-01/02 one source per region', () => {
  it('OCR line over native text is dropped, so text appears once', () => {
    const native = [L('Generated By', 50, 100, 100, 14, 'native', 1)]
    const ocr = [L('Generated By', 52, 101, 98), L('Page Count', 50, 140, 90)]
    const r = buildPageResult({ nativeLines: native, ocrLines: ocr, width: W, height: H })
    expect(r.text.split('Generated By').length - 1).toBe(1)
    expect(r.text).toContain('Page Count')
    expect(r.lines.filter(l => l.source !== 'native')).toHaveLength(1)
  })
  it('exact duplicate OCR lines collapse', () => {
    const ocr = [L('Page 1', 50, 100, 50), L('Page 1', 50, 100, 50)]
    const r = buildPageResult({ ocrLines: ocr, width: W, height: H })
    expect(r.lines).toHaveLength(1)
  })
  it('native garbage is rejected', () => {
    expect(isNativeGood([{ text: '\uFFFD\uFFFD\uFFFD\uE001\uE002 abc def ghi jkl' }])).toBe(false)
    expect(isNativeGood([{ text: 'This is a real sentence of text.' }])).toBe(true)
  })
  it('similarity is fuzzy', () => {
    expect(similarity('Checksum', 'checksum ')).toBe(1)
    expect(similarity('abcdefghij', 'abcdefghix') >= 0.85).toBe(true)
  })
})

describe('BUG-10 reading order', () => {
  it('title, then column 1 fully, then column 2', () => {
    const lines = [L('TWO COLUMN TITLE THAT SPANS THE WHOLE PAGE WIDTH OK', 50, 100, 500)]
    for (let i = 0; i < 4; i++) {
      lines.push(L(`left column text line number ${i}`, 50, 140 + i * 20, 230))
      lines.push(L(`right column text line number ${i}`, 330, 140 + i * 20, 230))
    }
    const r = reconstructPageLayout(lines, W, H)
    const t = r.fullText
    expect(t.indexOf('left column text line number 3')).toBeLessThan(t.indexOf('right column text line number 0'))
    expect(t.indexOf('TWO COLUMN')).toBeLessThan(t.indexOf('left column text line number 0'))
  })
})

describe('BUG-09 tables', () => {
  const lines = [L('ENTERPRISE CLUSTER MATRIX', 50, 100, 500)]
  const rows = [['Name', 'CPU', 'RAM', 'Cost'], ['alpha', '8', '32', '120'], ['beta', '16', '64', '240']]
  rows.forEach((r, ri) => r.forEach((c, ci) => lines.push(L(c, 50 + ci * 130, 140 + ri * 30, 80))))
  it('merged header emitted once with colspan 4', () => {
    const r = reconstructPageLayout(lines, W, H)
    expect(r.tables).toHaveLength(1)
    expect(r.tables[0].html).toContain('colspan="4"')
    expect(r.fullText.split('ENTERPRISE CLUSTER MATRIX').length - 1).toBe(1)
    expect(r.tables[0].markdown).toContain('| alpha | 8 | 32 | 120 |')
  })
  it('wrapped cell text joins into one cell', () => {
    const ls = [L('Reporting', 50, 100, 80), L('Status', 200, 100, 80), L('Category', 50, 116, 80),
      L('alpha', 50, 160, 80), L('ok', 200, 160, 80), L('beta', 50, 200, 80), L('bad', 200, 200, 80)]
    const r = reconstructPageLayout(ls, W, H)
    expect(r.tables[0].markdown).toContain('Reporting Category')
  })
  it('prose columns are not tables', () => {
    const ls = []
    for (let i = 0; i < 5; i++) {
      ls.push(L(`this is a long line of prose text in the left column ${i}`, 50, 140 + i * 20, 230))
      ls.push(L(`this is a long line of prose text in the right column ${i}`, 330, 140 + i * 20, 230))
    }
    expect(reconstructPageLayout(ls, W, H).tables).toHaveLength(0)
  })
})

describe('BUG-05 code blocks', () => {
  it('keeps indentation on a 4-space grid, fenced', () => {
    const cw = 7
    const src = ['def convert(path):', '    header = read(path)', '    if header:', '        return 1', '    return 0']
    const lines = src.map((s, i) => L(s.trim(), 50 + (s.length - s.trimStart().length) * cw, 200 + i * 18, s.trim().length * cw))
    const r = reconstructPageLayout(lines, W, H)
    expect(r.fullText).toContain('```')
    expect(r.fullText).toContain('\n        return 1')
    expect(r.fullText).toContain('\n    header = read(path)')
    expect(r.fullText).toContain('def convert(path):')
  })
})

describe('BUG-11 list nesting', () => {
  it('indents by x level, keeps legal numbering verbatim', () => {
    const lines = [
      L('• Level one item', 50, 200, 120),
      L('• Level two item', 80, 220, 120),
      L('• Level three item', 110, 240, 130),
      L('14.1 Clause text here', 50, 280, 150),
      L('14.2 Another clause', 50, 300, 150),
    ]
    const t = reconstructPageLayout(lines, W, H).fullText
    expect(t).toContain('- Level one item')
    expect(t).toContain('\n  - Level two item')
    expect(t).toContain('\n    - Level three item')
    expect(t).toContain('14.1 Clause text here')
  })
})

describe('BUG-13 form fields', () => {
  it('detects checkbox, radio (selected), text line, signature', () => {
    const ls = [
      { text: '[ ] Agree to terms', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: '[x] Subscribe', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: '( ) 3- Good', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: '(X) 4- Excellent', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: 'Comments: ________________', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
      { text: 'Signature: ________', xMin: 0, yMin: 0, xMax: 1, yMax: 1 },
    ]
    const f = detectFormFields(ls)
    expect(f.filter(x => x.type === 'checkbox')).toHaveLength(2)
    expect(f.filter(x => x.type === 'radio' && x.state === 'checked')).toHaveLength(1)
    expect(f.filter(x => x.type === 'text')).toHaveLength(1)
    expect(f.filter(x => x.type === 'signature')).toHaveLength(1)
  })
})
